class I18n:
    _current_lang: str = "en"

    @classmethod
    def set_language(cls, lang_code: str):
        if lang_code in TRANSLATIONS:
            cls._current_lang = lang_code

    @classmethod
    def get_language(cls) -> str:
        return cls._current_lang

    @classmethod
    def tr(cls, key: str, *args) -> str:
        lang_dict = TRANSLATIONS.get(cls._current_lang, TRANSLATIONS["en"])
        template = lang_dict.get(key, TRANSLATIONS["en"].get(key, key))
        if args:
            try:
                return template.format(*args)
            except Exception:
                return template
        return template


def tr(key: str, *args) -> str:
    return I18n.tr(key, *args)
